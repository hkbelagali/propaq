"""Rust emitter output, regen drift, and the build pipeline up to cargo check."""

import os
import re
import shutil
from pathlib import Path

import pytest

from propaq.tracer import build, regen
from propaq.tracer.analysis import add_fold
from propaq.tracer.bases import ALL
from propaq.tracer.build import BuildError, BuildUnavailable, build_basis, compile_spec, crate_files
from propaq.tracer.emit_rust import camel, emit_rust

REPO = Path(__file__).resolve().parents[2]
HAVE_TREE = (REPO / "crates" / "core" / "Cargo.toml").is_file()
needs_tree = pytest.mark.skipif(not HAVE_TREE, reason="needs the propaq source tree")
needs_cargo = pytest.mark.skipif(shutil.which("cargo") is None, reason="cargo not found")


def src_of(name):
    return emit_rust(add_fold(ALL[name]().trace_ir()))


def fn_body(src, name):
    m = re.search(rf"fn {name}\b.*?\n    }}\n", src, re.S)
    assert m, name
    return m.group(0)


@pytest.mark.parametrize("name", sorted(ALL))
def test_emitted_impl_shape(name):
    src = src_of(name)
    ty = camel(ALL[name]().name)
    assert f"impl<const W: usize> Basis<W> for {ty}" in src
    assert f"pub struct {ty}GenContext<const W: usize>" in src
    assert "const KIND: BasisKind = BasisKind::Custom;" in src
    assert "fn make_signed_gen_context" in src and "fn linear_fold" in src
    assert "Generated by propaq.tracer" in src


@pytest.mark.parametrize("name", sorted(ALL))
def test_no_per_term_allocation(name):
    src = src_of(name)
    per_term = "".join(fn_body(src, f) for f in ("character", "product", "weight", "trace"))
    if name == "z4":
        per_term += fn_body(src, "branch")
    for bad in (r"\bVec\b", r"vec!", r"\bBox\b", r"collect", r"to_vec", r"\bString\b", r"\.push\("):
        assert not re.search(bad, per_term), bad


def test_only_branch_table_allocates_and_only_for_many_branches():
    assert "Vec<Complex64>" not in src_of("pauli") and "weyl_table" not in src_of("majorana")
    z4 = src_of("z4")
    assert "fn branch_table" in z4 and "weyl_table(ctx.h" in z4


def test_emitted_constants_follow_the_spec():
    z4 = src_of("z4")
    assert "const BRANCHES: usize = 4;" in z4 and "const CHAR_MODULUS: u32 = 4;" in z4
    p = src_of("pauli")
    assert "const BRANCHES: usize = 2;" in p and "const PHASE_ORDER: u32 = 4;" in p
    assert "fn branch(" not in p  # the default (product) is used


def test_generator_only_work_is_outside_per_term_functions():
    # Pauli: popcount of the generator's Y sites must be computed once per gate.
    src = src_of("pauli")
    assert "popcount(&k" in fn_body(src, "make_signed_gen_context")
    assert src.count("popcount(") < 12
    assert "ctx.h" in fn_body(src, "product")


def test_majorana_weight_uses_runtime_unit_count():
    w = fn_body(src_of("majorana"), "weight")
    assert "active_bits::<W>(n_units * 2)" in w and "prefix_parity" in w


def test_emitter_is_deterministic():
    assert src_of("z4") == src_of("z4")


def test_weyl_table_needs_matching_orders():
    spec = ALL["z4"]()
    spec.phase_order = 8
    with pytest.raises(NotImplementedError):
        emit_rust(add_fold(spec.trace_ir()))


@needs_tree
def test_generated_crate_has_no_drift():
    assert regen.main(["--check", "--root", str(REPO)]) == 0


@needs_tree
def test_regen_writes_to_a_fresh_root(tmp_path):
    assert regen.main(["--root", str(tmp_path)]) == 0
    generated = regen.generate()
    for name in ALL:
        rel = f"crates/traced/src/{name}.rs"
        assert (tmp_path / rel).read_text() == generated[rel]
        if name == "z4":
            assert generated[rel] == src_of(name)
        else:
            # The built-ins differ from the generic emit only in their BasisKind line.
            kind = "Pauli" if name == "pauli" else "Majorana"
            assert generated[rel] == src_of(name).replace("BasisKind::Custom;", f"BasisKind::{kind};")
    assert (tmp_path / "crates/traced/tests/data/z4_table.in").is_file()
    assert regen.main(["--check", "--root", str(tmp_path)]) == 0
    (tmp_path / "crates/traced/src/pauli.rs").write_text("// changed\n")
    assert regen.main(["--check", "--root", str(tmp_path)]) == 1


@needs_tree
def test_crate_files(monkeypatch):
    monkeypatch.setenv("PROPAQ_SOURCE_DIR", str(REPO))
    ir = compile_spec(ALL["pauli"]())
    files = crate_files(ir, build.source_dir(), with_module=True)
    h = ir.hash16()
    assert f'name = "propaq_basis_{h}"' in files["Cargo.toml"]
    assert f'propaq-core = {{ path = "{REPO.as_posix()}/crates/core" }}' in files["Cargo.toml"]
    assert "cdylib" in files["Cargo.toml"] and "[workspace]" in files["Cargo.toml"]
    lib = files["src/lib.rs"]
    assert "propaq_core::define_raw_basis_module! {" in lib
    assert f"module: propaq_basis_{h}," in lib and "algebra: Pauli," in lib
    assert "bits_per_unit: 2," in lib and "coeff: f64," in lib
    assert 'pyo3-stub-gen' in files["Cargo.toml"]
    z4 = crate_files(compile_spec(ALL["z4"]()), build.source_dir(), with_module=True)
    assert "coeff: propaq_core::basis_module::Cx," in z4["src/lib.rs"]
    assert files["ir.json"] == ir.to_json()
    no_mod = crate_files(ir, build.source_dir(), with_module=False)
    assert "define_raw_basis_module" not in no_mod["src/lib.rs"]


