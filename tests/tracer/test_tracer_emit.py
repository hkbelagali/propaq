@pytest.fixture(scope="module")
def bases_cache(tmp_path_factory):
    """One cache for all cargo checks, so that the dependencies build once."""
    return os.environ.get("PROPAQ_TEST_CACHE") or str(tmp_path_factory.mktemp("bases"))


@needs_tree
@needs_cargo
@pytest.mark.parametrize("name", sorted(ALL))
def test_generated_crate_passes_cargo_check(name, monkeypatch, bases_cache):
    monkeypatch.setenv("PROPAQ_SOURCE_DIR", str(REPO))
    monkeypatch.setenv("PROPAQ_CACHE_DIR", bases_cache)
    try:
        res = build_basis(ALL[name](), check_only=True, jobs=4)
    except BuildError as e:
        if "index.crates.io" in str(e) or "failed to download" in str(e):
            pytest.skip("crates.io not reachable")
        raise
    assert res.checked_only and res.crate_dir.name == res.hash16
    again = res.crate_dir / "src" / "lib.rs"
    stamp = again.stat().st_mtime_ns
    build_basis(ALL[name](), check_only=True, jobs=4)
    assert again.stat().st_mtime_ns == stamp  # cache key hit: files are not rewritten
